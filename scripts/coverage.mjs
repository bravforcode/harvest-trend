import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
// Reads the `id: '...'` values between two markers in src/lib/data.ts.
const idsIn = (text, from, to) => {
  const start = text.indexOf(from);
  const block = text.slice(start, text.indexOf(to, start));
  return [...block.matchAll(/\bid:\s*'([^']+)'/g)].map((m) => m[1]);
};

// Counts (province, crop) pairs that have a real source.
// prov === '*' means a national dataset: it covers every province for that crop.
export function coverage(sources, provinces, crops) {
  const provincial = new Set();
  const national = new Set();
  for (const s of sources) {
    if (!crops.includes(s.crop)) continue;
    for (const p of provinces) {
      const key = p + '|' + s.crop;
      if (s.prov === p) provincial.add(key);
      else if (s.prov === '*') national.add(key);
    }
  }
  const nationalOnly = [...national].filter((k) => !provincial.has(k)).length;
  return {
    total: provinces.length * crops.length,
    provincial: provincial.size,
    national: nationalOnly,
    covered: provincial.size + nationalOnly,
  };
}

export function main() {
  const text = readFileSync(join(ROOT, 'src/lib/data.ts'), 'utf8');
  const provinces = idsIn(text, 'PROVINCES: NORTH', 'export const PROVINCES');
  const crops = idsIn(text, 'export const CROPS', '\n];');
  // api/prices.js is CommonJS and exposes its registry via _internals.
  const sources = createRequire(import.meta.url)('../api/prices.js')._internals.SOURCES;
  const r = coverage(sources, provinces, crops);
  const uncovered = r.total - r.covered;
  const md = [
    '# Real-data coverage of province × crop pairs',
    '',
    'Generated by `node scripts/coverage.mjs`. Do not edit by hand.',
    '',
    'Inputs: `SOURCES` (`api/prices.js`, `module.exports._internals`), provinces and crops (`src/lib/data.ts`).',
    '',
    `Provinces: ${provinces.length}. Crops: ${crops.length}. Source entries: ${sources.length}.`,
    '',
    '| Measure | Pairs |',
    '|---|---|',
    `| Total (province × crop) | ${r.total} |`,
    `| Provincial real data | ${r.provincial} |`,
    `| National-only data | ${r.national} |`,
    `| Uncovered | ${uncovered} |`,
    `| Covered (provincial + national-only) | ${r.covered} |`,
    '',
    '## Sources per crop',
    '',
    '| Crop | Source entries |',
    '|---|---|',
    ...crops.map((c) => `| ${c} | ${sources.filter((s) => s.crop === c).length} |`),
    '',
  ].join('\n');
  mkdirSync(join(ROOT, 'docs/funding'), { recursive: true });
  writeFileSync(join(ROOT, 'docs/funding/coverage-table.md'), md);
  console.log(JSON.stringify({ provinces: provinces.length, crops: crops.length, ...r, uncovered }));
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) main();
